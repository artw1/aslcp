package nxdn

// scrambler is the 48-byte RF frame whitening sequence (MMDVMHost
// NXDNControl.cpp SCRAMBLER). The first 3 bytes (frame sync word) are not
// whitened.
var scrambler = [FrameBytes]byte{
	0x00, 0x00, 0x00, 0x82, 0xA0, 0x88, 0x8A, 0x00, 0xA2, 0xA8, 0x82, 0x8A, 0x82, 0x02,
	0x20, 0x08, 0x8A, 0x20, 0xAA, 0xA2, 0x82, 0x08, 0x22, 0x8A, 0xAA, 0x08, 0x28, 0x88,
	0x28, 0x28, 0x00, 0x0A, 0x02, 0x82, 0x20, 0x28, 0x82, 0x2A, 0xAA, 0x20, 0x22, 0x80,
	0xA8, 0x8A, 0x08, 0xA0, 0xAA, 0x02,
}

// Scramble XORs a 48-byte RF frame with the scrambler sequence (it is its own
// inverse).
func Scramble(frame []byte) {
	for i := 0; i < FrameBytes && i < len(frame); i++ {
		frame[i] ^= scrambler[i]
	}
}
